const _: () = {
    let mut i = 0;
    while i < CODES.len() {
        assert!(
            CODES[i] == i as u32,
            "origami_key is out of step with the key list"
        );
        i += 1;
    }
};

/// The key a frame-plane code names.
pub(crate) fn from_code(code: u32) -> Option<Key> {
    ALL.get(code as usize).copied()
}
